export const emojiMap = FOOD_GROUPS.flatMap((group) => group.subcategories.flatMap((subcategory) => subcategory.items)).reduce(
  (map, [name, emoji]) => ({ ...map, [name]: emoji }),
  {},
);

export function defaultExpiryDate(category) {
  const days = CATEGORY_EXPIRY_DAYS[category] ?? 7;
  return new Date(Date.now() + days * 24 * 60 * 60 * 1000).toISOString().slice(0, 10);
}

export function findFoodGroup(category) {
  return FOOD_GROUPS.find((group) => group.label === category) || FOOD_GROUPS[0];
}

export function findSubcategory(group, subcategory) {
  return group.subcategories.find((item) => item.label === subcategory) || group.subcategories[0];
}
